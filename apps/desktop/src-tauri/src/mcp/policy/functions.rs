const DENIED_RELATIONS: &[&str] = &[
    "pg_authid",
    "pg_shadow",
    "pg_largeobject",
    "pg_user_mapping",
    "pg_user_mappings",
    "pg_statistic",
];

fn family_functions(family: SqlFamily) -> &'static [&'static str] {
    match family {
        SqlFamily::Postgres => POSTGRES,
        SqlFamily::MySql => MYSQL,
        SqlFamily::Sqlite => SQLITE,
        SqlFamily::HogQl => &[],
    }
}

pub fn is_allowed_function(family: SqlFamily, name: &str, allow_write_functions: bool) -> bool {
    COMMON.contains(&name)
        || family_functions(family).contains(&name)
        || (allow_write_functions && WRITE_FUNCTIONS.contains(&name))
}

pub fn is_allowed_table_function(family: SqlFamily, name: &str) -> bool {
    HOST_TABLE_FUNCTIONS.contains(&name) && family_functions(family).contains(&name)
}

pub fn is_denied_relation(family: SqlFamily, parts: &[String]) -> bool {
    let Some(last) = parts.last() else {
        return true;
    };
    if DENIED_RELATIONS.contains(&last.as_str()) {
        return true;
    }
    family == SqlFamily::MySql
        && parts.len() > 1
        && matches!(
            parts[parts.len() - 2].as_str(),
            "mysql" | "performance_schema" | "sys"
        )
}
